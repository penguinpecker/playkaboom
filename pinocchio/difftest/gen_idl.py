#!/usr/bin/env python3
"""Generate src/idl.rs (ix builders, account structs, event names) from the Anchor IDL.

The IDL is target/idl/kaboom.json (spec shared.md: "matches HEAD e82f2c5"); tests/spec_table.rs checks the
output against spec/shared.md section 9. The old program id in the IDL is replaced with the new one.
Run: python3 -I gen_idl.py   (rewrites src/idl.rs; commit-free, deterministic)
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
IDL = os.path.join(HERE, "../../target/idl/kaboom.json")
OUT = os.path.join(HERE, "src/idl.rs")
OLD_ID, NEW_ID = "9Xip2LRCgC8ucvkYuBQ8jzEsPV74YBnFG1BBeZa98QSh", "Ednka8zjoYbE7T6iF9NHHXotaXCrbJn4Mta376cunhju"
SPACE = {"GameSession": 180, "LpPosition": 121, "PlayerStats": 203, "ReferralAccount": 103, "Vault": 428,
         "VaultV2State": 191, "VrfClaim": 69, "VrfGame": 621}

d = json.load(open(IDL))
types = {t["name"]: t for t in d["types"]}


def pascal(s):
    return "".join(p[:1].upper() + p[1:] for p in s.split("_"))


def rty(t):
    if isinstance(t, str):
        return {"u8": "u8", "u16": "u16", "u32": "u32", "u64": "u64", "i64": "i64", "u128": "u128",
                "bool": "bool", "pubkey": "Address", "bytes": "Vec<u8>"}[t]
    if "array" in t:
        return f"[{rty(t['array'][0])}; {t['array'][1]}]"
    if "option" in t:
        return f"Option<{rty(t['option'])}>"
    if "vec" in t:
        return f"Vec<{rty(t['vec'])}>"
    return t["defined"]["name"]


def addr(s):
    return f'Address::from_str_const("{NEW_ID if s == OLD_ID else s}")'


o = ["// @generated by gen_idl.py from target/idl/kaboom.json. Do not edit by hand.",
     "#![allow(clippy::all, non_snake_case)]",
     "use borsh::{BorshDeserialize, BorshSerialize};",
     "use solana_address::Address;",
     "use solana_instruction::{AccountMeta, Instruction};",
     "",
     f'pub const PROGRAM_ID: Address = Address::from_str_const("{NEW_ID}");',
     "",
     "/// Account types (Borsh after the 8-byte discriminator). `decode` checks the disc; `encode` pads to SPACE.",
     "pub mod accounts {",
     "    use super::*;"]
emitted = set()


def emit_type(name):
    if name in emitted:
        return
    emitted.add(name)
    t = types[name]["type"]
    if t["kind"] == "enum":
        o.append("    #[derive(BorshSerialize, BorshDeserialize, Debug, Clone, Copy, PartialEq, Eq, Default)]")
        o.append("    #[borsh(use_discriminant = false)]")
        o.append(f"    pub enum {name} {{")
        for i, v in enumerate(t["variants"]):
            o.append(("        #[default]\n" if i == 0 else "") + f"        {v['name']},")
        o.append("    }")
        return
    for f in t["fields"]:
        ft = f["type"]
        while isinstance(ft, dict) and ("array" in ft or "option" in ft):
            ft = ft.get("array", [None])[0] if "array" in ft else ft["option"]
        if isinstance(ft, dict) and "defined" in ft:
            emit_type(ft["defined"]["name"])
    o.append("    #[derive(BorshSerialize, BorshDeserialize, Debug, Clone, PartialEq, Eq)]")
    o.append(f"    pub struct {name} {{")
    for f in t["fields"]:
        o.append(f"        pub {f['name']}: {rty(f['type'])},")
    o.append("    }")


for a in d["accounts"]:
    n = a["name"]
    emit_type(n)
    o.append(f"    impl {n} {{")
    o.append(f"        pub const DISC: [u8; 8] = {a['discriminator']};")
    o.append(f"        pub const SPACE: usize = {SPACE[n]};")
    o.append("        pub fn decode(data: &[u8]) -> std::io::Result<Self> {")
    o.append("            if data.len() < 8 || data[..8] != Self::DISC { return Err(std::io::Error::other(\"discriminator\")); }")
    o.append("            Self::deserialize(&mut &data[8..])")
    o.append("        }")
    o.append("        pub fn encode(&self) -> Vec<u8> {")
    o.append("            let mut v = Self::DISC.to_vec();")
    o.append("            self.serialize(&mut v).unwrap();")
    o.append("            assert!(v.len() <= Self::SPACE);")
    o.append("            v.resize(Self::SPACE, 0);")
    o.append("            v")
    o.append("        }")
    o.append("    }")
o.append("}")
o.append("")

o.append("/// Instruction builders: one struct per instruction, fields = accounts in IDL order.")
o.append("/// `Default` pre-fills fixed addresses (programs, sysvars, oracle queue) and constant-seed PDAs")
o.append("/// (vault, v2_state, program_identity); every other key defaults to the zero address.")
o.append("/// `.ix(args..)` returns the Instruction; push `remaining_accounts` onto `ix.accounts` yourself.")
o.append("pub mod ix {")
o.append("    use super::*;")
table = []
for i in d["instructions"]:
    n, P = i["name"], pascal(i["name"])
    o.append(f"    #[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    o.append(f"    pub struct {P} {{")
    for a in i["accounts"]:
        o.append(f"        pub {a['name']}: Address,")
    o.append("    }")
    o.append(f"    impl Default for {P} {{")
    o.append("        fn default() -> Self {")
    o.append("            Self {")
    for a in i["accounts"]:
        v = "Address::new_from_array([0; 32])"
        if "address" in a:
            v = addr(a["address"])
        elif "pda" in a and "program" not in a["pda"] and all(s["kind"] == "const" for s in a["pda"]["seeds"]):
            seeds = ", ".join(f"&{s['value']}" for s in a["pda"]["seeds"])
            v = f"Address::find_program_address(&[{seeds}], &PROGRAM_ID).0"
        o.append(f"                {a['name']}: {v},")
    o.append("            }")
    o.append("        }")
    o.append("    }")
    o.append(f"    impl {P} {{")
    o.append(f"        pub const DISC: [u8; 8] = {i['discriminator']};")
    o.append(f"        pub const NAME: &'static str = \"{P}\";")
    o.append(f"        /// Account names with (writable, signer), IDL order.")
    flags = ", ".join(f"(\"{a['name']}\", {str(a.get('writable', False)).lower()}, {str(a.get('signer', False)).lower()})" for a in i["accounts"])
    o.append(f"        pub const ACCOUNTS: &'static [(&'static str, bool, bool)] = &[{flags}];")
    args = ", ".join(f"{a['name']}: {rty(a['type'])}" for a in i["args"])
    o.append(f"        pub fn ix(&self{', ' if args else ''}{args}) -> Instruction {{")
    o.append("            #[allow(unused_mut)]")
    o.append("            let mut data = Self::DISC.to_vec();")
    for a in i["args"]:
        o.append(f"            BorshSerialize::serialize(&{a['name']}, &mut data).unwrap();")
    o.append("            let accounts = vec![")
    for a in i["accounts"]:
        w, s = a.get("writable", False), a.get("signer", False)
        ctor = "AccountMeta::new" if w else "AccountMeta::new_readonly"
        o.append(f"                {ctor}(self.{a['name']}, {str(s).lower()}),")
    o.append("            ];")
    o.append("            Instruction { program_id: PROGRAM_ID, accounts, data }")
    o.append("        }")
    o.append("    }")
    table.append(f"        ({P}::DISC, {P}::NAME, {P}::ACCOUNTS),")
o.append("    /// (disc, log name, accounts) for all instructions, IDL order.")
o.append("    pub const ALL: &[([u8; 8], &str, &[(&str, bool, bool)])] = &[")
o.extend(table)
o.append("    ];")
o.append("    pub fn by_disc(data: &[u8]) -> Option<&'static ([u8; 8], &'static str, &'static [(&'static str, bool, bool)])> {")
o.append("        ALL.iter().find(|e| data.len() >= 8 && data[..8] == e.0)")
o.append("    }")
o.append("}")
o.append("")
o.append("/// (event disc, event name) for every `#[event]`.")
o.append("pub const EVENTS: &[([u8; 8], &str)] = &[")
for e in d["events"]:
    o.append(f"    ({e['discriminator']}, \"{e['name']}\"),")
o.append("];")
o.append("/// Error names: (code, name), 6000+ custom codes.")
o.append("pub const ERRORS: &[(u32, &str)] = &[")
for e in d["errors"]:
    o.append(f"    ({e['code']}, \"{e['name']}\"),")
o.append("];")

open(OUT, "w").write("\n".join(o) + "\n")
print(f"wrote {OUT}: {len(d['instructions'])} ix, {len(d['accounts'])} accounts, {len(d['events'])} events")
