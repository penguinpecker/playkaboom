// Writes fixtures/sdk_ixs.txt: instructions built by the TypeScript SDK
// (packages/sdk) for the keys the Rust harness uses, so tests/sdk_flows.rs can
// run the exact bytes the web app sends against the port .so.
//
//   npx tsx pinocchio/difftest/sdk_fixture.ts      (from the repo root)
//
// Line format: <name> <program id> <data hex> <pubkey>:<W|r>:<S|->,...
// Keys mirror difftest `key(label)` = sha256(label) and `DEPLOYER`.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { PublicKey, SystemProgram, type TransactionInstruction } from "@solana/web3.js";
import {
  buildCancelWithdraw,
  buildCashOutVrf,
  buildCompleteWithdraw,
  buildDelegateVrf,
  buildExpireGame,
  buildForceUndelegateVrf,
  buildFundVault,
  buildInitializeV2,
  buildInitializeVault,
  buildLpDeposit,
  buildRefundStalledVrf,
  buildRequestWithdraw,
  buildRevealRequestVrf,
  buildSetReferrer,
  buildSettleAndUndelegateVrf,
  buildSettleVrf,
  buildStartGameVrf,
  buildUpdateV2Config,
  deriveReferralPda,
} from "@playkaboom/sdk";
import { KABOOM_DEPLOYER, KABOOM_PROGRAM_ID } from "@playkaboom/shared";

const key = (label: string) => new PublicKey(createHash("sha256").update(label).digest());
const ctx = { programId: new PublicKey(KABOOM_PROGRAM_ID) };
const SOL = 1_000_000_000n;
const deployer = new PublicKey(KABOOM_DEPLOYER);
const house = key("house");
const treasury = key("treasury");
const validator = key("validator");
const referrer = key("referrer");
const player = key("player");
const player2 = key("player2");
const player3 = key("player3");
const legacy = key("legacy");
const lp = key("lp");
const session = key("session");
const session2 = key("session2");
const session3 = key("session3");

const ixs: Record<string, TransactionInstruction> = {
  // vault bootstrap (same args as Pair::house_world + enable_vrf)
  initialize_vault: buildInitializeVault({ ctx, owner: deployer, houseAuthority: house, treasury, houseEdgeBps: 100, maxBetBps: 100, maxPayoutBps: 1_000 }),
  fund_vault: buildFundVault({ ctx, funder: deployer, amount: 50n * SOL }),
  initialize_v2: buildInitializeV2({ ctx, owner: deployer }),
  enable_vrf: buildUpdateV2Config({ ctx, owner: deployer, vrfModeEnabled: true, vrfValidator: validator, vrfMaxPayoutBps: 1_000 }),
  // the web start tx: [set_referrer?, start_game_vrf, fund session, delegate_vrf] (lib/vrf/client.ts)
  set_referrer: buildSetReferrer({ ctx, player, referrer }),
  start_game_vrf: buildStartGameVrf({ ctx, player, mineCount: 1, betLamports: 10_000_000n, sessionKey: session }),
  fund_session: SystemProgram.transfer({ fromPubkey: player, toPubkey: session, lamports: 2_000_000 }),
  delegate_vrf: buildDelegateVrf({ ctx, player }),
  // ER
  reveal_request_vrf: buildRevealRequestVrf({ ctx, player, session, tileIndex: 5, clientSeed: 9 }),
  cash_out_vrf: buildCashOutVrf({ ctx, player, signer: session }),
  settle_and_undelegate_vrf: buildSettleAndUndelegateVrf({ ctx, player, payer: session }),
  // L1 settle by the house, referral PDA mandatory for a referred player (F5)
  settle_vrf_referred: buildSettleVrf({ ctx, player, payer: house, treasury, referralPda: deriveReferralPda(ctx.programId, referrer)[0] }),
  // never-delegated start, refunded by the house (cron 9.3.c')
  start_game_vrf_2: buildStartGameVrf({ ctx, player: player2, mineCount: 1, betLamports: 10_000_000n, sessionKey: session2 }),
  refund_stalled_vrf_2: buildRefundStalledVrf({ ctx, player: player2, caller: house }),
  // F3: idle delegated game forced on the ER, then the VOID refund (9.3.b, c)
  start_game_vrf_3: buildStartGameVrf({ ctx, player: player3, mineCount: 1, betLamports: 10_000_000n, sessionKey: session3 }),
  delegate_vrf_3: buildDelegateVrf({ ctx, player: player3 }),
  force_undelegate_vrf_3: buildForceUndelegateVrf({ ctx, player: player3, house }),
  refund_stalled_vrf_3: buildRefundStalledVrf({ ctx, player: player3, caller: house }),
  // F2 legacy wind-down (9.3.d)
  expire_game: buildExpireGame({ ctx, player: legacy }),
  // LP (F4: keeper completes unsigned; restart = cancel + request same units)
  lp_deposit: buildLpDeposit({ ctx, user: lp, amountLamports: SOL }),
  request_withdraw: buildRequestWithdraw({ ctx, user: lp, units: 500_000_000n }),
  complete_withdraw_unsigned: buildCompleteWithdraw({ ctx, user: lp, userSigns: false }),
  complete_withdraw_signed: buildCompleteWithdraw({ ctx, user: lp }),
  cancel_withdraw: buildCancelWithdraw({ ctx, user: lp }),
};

const lines = Object.entries(ixs).map(([name, ix]) =>
  [
    name,
    ix.programId.toBase58(),
    Buffer.from(ix.data).toString("hex") || "-",
    ix.keys.map((k) => `${k.pubkey.toBase58()}:${k.isWritable ? "W" : "r"}:${k.isSigner ? "S" : "-"}`).join(","),
  ].join(" "),
);
const out = join(__dirname, "fixtures", "sdk_ixs.txt");
writeFileSync(out, `# generated by sdk_fixture.ts from packages/sdk — do not edit\n${lines.join("\n")}\n`);
console.log(`wrote ${lines.length} instructions to ${out}`);
